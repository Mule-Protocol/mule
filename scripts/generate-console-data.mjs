/**
 * Build-only generation from the reviewed fixtures and Ajv standalone compiler.
 * Browser code imports these generated functions; it never constructs Ajv.
 * Source: https://ajv.js.org/standalone.html
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const requireValidator = createRequire(resolve(root, 'packages/validator/package.json'));
const requireLogic = createRequire(resolve(root, 'packages/mission-logic/package.json'));
const { canonicalJson, MODELS } = requireLogic('./dist/index.js');
const Ajv2020 = requireValidator('ajv/dist/2020.js').default;
const addFormats = requireValidator('ajv-formats').default;
const standaloneCode = requireValidator('ajv/dist/standalone/index.js').default;
const ajv = new Ajv2020({
  allErrors: true, strict: true, coerceTypes: false, useDefaults: false, removeAdditional: false,
  code: { source: true, esm: true },
});
addFormats(ajv, ['date']);

const fixtures = Object.fromEntries(MODELS.map(model => {
  const directory = resolve(root, 'fixtures', model);
  const criteria = JSON.parse(readFileSync(resolve(directory, 'criteria.json'), 'utf8'));
  const input = JSON.parse(readFileSync(resolve(directory, 'input.json'), 'utf8'));
  if (criteria.model !== model) throw new Error('Fixture model mismatch: ' + model);
  // Same encoder as Node and the browser, including its rejection of lossy values.
  canonicalJson({ criteria, input });
  return [model, { criteria, input }];
}));
const schemas = new Map();
function visit(schema) {
  if (!schema || typeof schema !== 'object' || Array.isArray(schema)) throw new Error('Unsupported curated schema');
  const key = canonicalJson(schema);
  if (schemas.has(key)) return;
  const name = 'schema' + schemas.size;
  const id = 'mule-standalone-' + name;
  schemas.set(key, { name, id, schema });
  // A separate validator for each schema preserves the same #/... error paths as ajv.compile.
  ajv.addSchema(schema, id);
  for (const property of Object.values(schema.properties ?? {})) visit(property);
  if (schema.items !== undefined) visit(schema.items);
}
for (const fixture of Object.values(fixtures)) visit(fixture.criteria.schema);

let standalone = standaloneCode(ajv, Object.fromEntries([...schemas.values()].map(({ name, id }) => [name, id])));
// Ajv standalone may emit static CommonJS helper references even with ESM exports.
// Convert only this reviewed allowlist to static ESM imports; never evaluate source.
const allowedHelpers = new Set([
  'ajv/dist/runtime/ucs2length',
  'ajv/dist/runtime/equal',
  'ajv-formats/dist/formats',
]);
const helperImports = new Map();
standalone = standalone.replace(/require\("([^"]+)"\)/g, (_match, specifier) => {
  if (!allowedHelpers.has(specifier)) throw new Error('Review new Ajv standalone helper before use: ' + specifier);
  if (!helperImports.has(specifier)) helperImports.set(specifier, 'standaloneHelper' + helperImports.size);
  return helperImports.get(specifier);
});
if (/\brequire\s*\(|\beval\s*\(|\bnew\s+Function\b/.test(standalone)) {
  throw new Error('Standalone output contains an unsupported runtime construct');
}
const header = '// Generated by scripts/generate-console-data.mjs; do not edit.\n';
const imports = [...helperImports].map(([specifier, name]) => 'import ' + name + ' from ' + JSON.stringify(specifier + '.js') + ';').join('\n');
const directory = resolve(root, 'packages/console-core/src/generated');
mkdirSync(directory, { recursive: true });
const write = (name, value) => writeFileSync(resolve(directory, name), value, 'utf8');
write('standalone.mjs', '/* eslint-disable -- Generated Ajv code; regenerate from reviewed schemas. */\n' + header + imports + '\n' + standalone + '\n');
write('standalone.d.mts', header + "import type { SchemaValidationFunction } from '@mule/mission-logic';\n"
  + [...schemas.values()].map(({ name }) => 'export const ' + name + ': SchemaValidationFunction;').join('\n') + '\n');
write('fixtures.ts', header
  + "import { canonicalJson, MODELS, type Fixture, type Model } from '@mule/mission-logic';\n\n"
  + 'const fixtures: Record<Model, Fixture> = ' + JSON.stringify(fixtures, null, 2) + ';\n\n'
  + "export function fixtureFor(model: Model): Fixture {\n"
  + "  if (!MODELS.includes(model)) throw new Error('Unsupported mission model');\n"
  + '  return JSON.parse(canonicalJson(fixtures[model])) as Fixture;\n}\n');
write('validators.ts', header
  + "import { canonicalJson, type SchemaValidationFunction } from '@mule/mission-logic';\n"
  + "import * as standalone from './standalone.mjs';\n\n"
  + 'const validators = new Map<string, SchemaValidationFunction>([\n'
  + [...schemas].map(([key, { name }]) => '  [' + JSON.stringify(key) + ', standalone.' + name + '],').join('\n') + '\n]);\n\n'
  + 'export function schemaValidator(schema: object): SchemaValidationFunction {\n'
  + '  const validate = validators.get(canonicalJson(schema));\n'
  + "  if (!validate) throw new Error('Unsupported schema; validators are compiled at build time');\n"
  + '  return validate;\n}\n');
console.log('Generated ' + MODELS.length + ' fixture models and ' + schemas.size + ' standalone schema validators.');
